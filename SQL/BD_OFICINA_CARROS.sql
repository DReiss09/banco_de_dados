SELECT C.NOME AS CLIENTE, 
    COUNT(V.ID) AS TOTAL_CARROS
FROM CLIENTES C
LEFT JOIN VEICULOS V ON C.ID = V.FK_CLIENTE_ID
GROUP BY C.ID, C.NOME;

SELECT  V.PLACA, 
		V.MARCA, 
		V.MODELO, 
		COUNT(A.ID) AS TOTAL_AGENDAMENTOS
FROM VEICULOS V
LEFT JOIN AGENDAMENTOS A ON V.ID = A.FK_VEICULO_ID
GROUP BY V.ID, V.PLACA, V.MARCA, V.MODELO;


SELECT C.NOME AS CLIENTE, 
    COUNT(A.ID) AS TOTAL_AGENDAMENTOS
FROM CLIENTES C
LEFT JOIN VEICULOS V ON C.ID = V.FK_CLIENTE_ID
LEFT JOIN AGENDAMENTOS A ON V.ID = A.FK_VEICULO_ID
GROUP BY C.ID, C.NOME;











