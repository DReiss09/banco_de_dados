CREATE DATABASE IF NOT EXISTS BD_MINI_PROJETO;
USE BD_MINI_PROJETO;

CREATE TABLE IF NOT EXISTS SENSOR_IOT(
	SEN_ID INT AUTO_INCREMENT PRIMARY KEY,
	SEN_MAC_ADDRESS VARCHAR(17) NOT NULL
);

CREATE TABLE IF NOT EXISTS USUARIO(
	USU_ID INT AUTO_INCREMENT PRIMARY KEY,
	USU_NOME VARCHAR(100) NOT NULL,
	USU_MATRICULA VARCHAR(50) NOT NULL,
	USU_SENHA VARCHAR(100) NOT NULL,
	USU_PERFIL VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS MAQUINA(
	MAQ_ID INT AUTO_INCREMENT PRIMARY KEY,
	MAQ_CODIGO_MAQUINA VARCHAR(50) NOT NULL,
	MAQ_TIPO_PECA VARCHAR(100),
	FK_SEN_ID INT,
	FOREIGN KEY (FK_SEN_ID) REFERENCES SENSOR_IOT(SEN_ID)
);

CREATE TABLE IF NOT EXISTS ALERTA(
	ALE_ID INT AUTO_INCREMENT PRIMARY KEY,
	ALE_TIPO_ALERTA VARCHAR(50) NOT NULL,
	ALE_MENSAGEM VARCHAR(255),
	ALE_DATA_HORA DATETIME,
	FK_MAQ_ID INT,
	FOREIGN KEY (FK_MAQ_ID) REFERENCES MAQUINA(MAQ_ID)
);

CREATE TABLE IF NOT EXISTS ENTRADA_OPERADOR(
	ENT_ID INT AUTO_INCREMENT PRIMARY KEY,
	ENT_PECAS_PRODUZIDAS INT,
	ENT_PECAS_REFUGADAS INT,
	ENT_MINUTOS_PARADA INT,
	FK_USU_ID INT,
	FK_TUR_ID INT,
	FK_MAQ_ID INT,
	FOREIGN KEY (FK_USU_ID) REFERENCES USUARIO(USU_ID),
	FOREIGN KEY (FK_MAQ_ID) REFERENCES MAQUINA(MAQ_ID)
);

CREATE TABLE IF NOT EXISTS TURNO(
	TUR_ID INT AUTO_INCREMENT PRIMARY KEY,
	TUR_NOME_TURNO VARCHAR(50) NOT NULL,
	TUR_HORARIO_INICIO TIME NOT NULL,
	TUR_HORARIO_FIM TIME NOT NULL,
	FK_ENT_ID INT,
	FOREIGN KEY (FK_ENT_ID) REFERENCES ENTRADA_OPERADOR(ENT_ID)
);

